document.addEventListener('DOMContentLoaded', () => {

    // 1. Mobile Menu Logic (Hamburger toggle)
    const menuIcon = document.querySelector('.menu-icon');
    const navLinks = document.querySelector('.nav-links');

    if (menuIcon && navLinks) {
        menuIcon.addEventListener('click', () => {
            navLinks.classList.toggle('active');
            const icon = menuIcon.querySelector('i');
            if (navLinks.classList.contains('active')) {
                icon.classList.remove('fa-bars');
                icon.classList.add('fa-times');
            } else {
                icon.classList.remove('fa-times');
                icon.classList.add('fa-bars');
            }
        });
    }

    // 2. Mobile Dropdown Accordion Toggle
    const dropdownToggles = document.querySelectorAll('.dropdown-toggle');
    dropdownToggles.forEach(toggle => {
        toggle.addEventListener('click', (e) => {
            if (window.innerWidth <= 900) {
                e.preventDefault(); // Prevent page navigation immediately on mobile
                const parent = toggle.parentElement;
                const menu = parent.querySelector('.dropdown-menu');
                
                // Toggle current dropdown active state
                const isActive = menu.classList.contains('active');
                
                // Close all other accordions
                document.querySelectorAll('.dropdown').forEach(d => {
                    d.classList.remove('open');
                    const m = d.querySelector('.dropdown-menu');
                    if (m) m.classList.remove('active');
                });
                
                if (!isActive) {
                    parent.classList.add('open');
                    if (menu) menu.classList.add('active');
                }
            }
        });
    });

    // 3. Global Lightbox Logic (For projects.html)
    const lightboxModal = document.getElementById('lightboxModal');
    const lightboxImg = document.getElementById('lightboxImg');
    const lightboxCaption = document.getElementById('lightboxCaption');

    if (lightboxModal) {
        lightboxModal.addEventListener('click', () => {
            lightboxModal.classList.remove('active');
        });
    }

    window.openLightbox = function (element) {
        if (!lightboxModal || !lightboxImg || !lightboxCaption) return;
        
        const img = element.querySelector('img');
        const h4 = element.querySelector('h4');
        const p = element.querySelector('p');
        
        lightboxImg.src = img.src;
        lightboxCaption.innerHTML = `<strong>${h4 ? h4.innerText : ''}</strong><br>${p ? p.innerText : ''}`;
        lightboxModal.classList.add('active');
    };

    // 4. Scroll Animations (IntersectionObserver)
    const observerOptions = {
        root: null,
        rootMargin: '0px',
        threshold: 0.1
    };

    const observer = new IntersectionObserver((entries, observer) => {
        entries.forEach(entry => {
            if (entry.isIntersecting) {
                entry.target.classList.add('active');
                observer.unobserve(entry.target);
            }
        });
    }, observerOptions);

    const revealElements = document.querySelectorAll('.reveal');
    revealElements.forEach(el => observer.observe(el));

    // 5. Header Scroll Logic (Sticky Transparent to Solid Blue)
    const header = document.querySelector('header');
    if (header) {
        window.addEventListener('scroll', () => {
            if (window.scrollY > 50) {
                header.classList.add('scrolled');
            } else {
                header.classList.remove('scrolled');
            }
        });
    }

    // 6. Hero Slider Logic
    const slides = document.querySelectorAll('.hero-slide');
    if (slides.length > 1) {
        let currentSlide = 0;
        setInterval(() => {
            slides[currentSlide].classList.remove('active');
            currentSlide = (currentSlide + 1) % slides.length;
            slides[currentSlide].classList.add('active');
        }, 5000);
    }

    // 7. Language Switcher Logic
    const langOptions = document.querySelectorAll('.lang-option');
    const langBtnText = document.querySelector('.lang-btn span');

    function setLanguage(lang) {
        const elements = document.querySelectorAll('[data-i18n]');
        elements.forEach(el => {
            const key = el.getAttribute('data-i18n');
            if (translations[lang] && translations[lang][key]) {
                el.innerHTML = translations[lang][key];
            }
        });

        if (langBtnText) langBtnText.textContent = lang.toUpperCase();
        localStorage.setItem('selectedLang', lang);
    }

    if (langBtnText && langBtnText.parentElement) {
        const langBtn = langBtnText.parentElement;
        langBtn.addEventListener('click', (e) => {
            e.stopPropagation();
            const dropdown = langBtn.nextElementSibling;
            if (dropdown) dropdown.classList.toggle('active');
        });

        document.addEventListener('click', (e) => {
            const dropdown = document.querySelector('.lang-dropdown');
            if (dropdown && dropdown.classList.contains('active') && !langBtn.contains(e.target)) {
                dropdown.classList.remove('active');
            }
        });
    }

    langOptions.forEach(opt => {
        opt.addEventListener('click', () => {
            const lang = opt.getAttribute('data-lang');
            setLanguage(lang);
            const dropdown = document.querySelector('.lang-dropdown');
            if (dropdown) dropdown.classList.remove('active');
        });
    });

    // Load saved language
    const savedLang = localStorage.getItem('selectedLang') || 'es';
    setLanguage(savedLang);

    // 8. Sectors Interactive Tabs (Homepage)
    window.openSector = function(evt, sectorId) {
        const panes = document.querySelectorAll('.sector-pane');
        panes.forEach(pane => {
            pane.classList.remove('active');
        });
        
        const tabBtns = document.querySelectorAll('.tab-btn');
        tabBtns.forEach(btn => {
            btn.classList.remove('active');
        });
        
        const activePane = document.getElementById(sectorId);
        if (activePane) {
            activePane.classList.add('active');
        }
        evt.currentTarget.classList.add('active');
    };

    // 9. Alert Success Flag Handling (From redirect parameters)
    const urlParams = new URLSearchParams(window.location.search);
    if (urlParams.has('success')) {
        const newUrl = window.location.pathname;
        window.history.replaceState({}, document.title, newUrl);

        if (typeof Swal !== 'undefined') {
            Swal.fire({
                title: '¡Solicitud Recibida!',
                text: 'Hemos registrado su solicitud técnica corporativa. Un ingeniero de nuestra oficina le contactará en menos de 48 horas.',
                icon: 'success',
                confirmButtonColor: '#0A2540'
            });
        } else {
            alert("Solicitud Recibida! Nos pondremos en contacto en menos de 48 horas.");
        }
    }

    // Submit button visual feedback
    const forms = document.querySelectorAll('form');
    forms.forEach(form => {
        form.addEventListener('submit', function () {
            const btn = this.querySelector('button[type="submit"]');
            if (btn) {
                btn.innerText = "Enviando Solicitud...";
                btn.style.opacity = '0.7';
            }
        });
    });

});
